#!/bin/bash
# Stage the bootstrap5 modules to test in assets/, and write assets/provisioning.yml to install them in
# dependency order: bootstrap5-core, bootstrap5-components, bootstrap5-templates-starter.
#
# By default the modules come from this checkout's Maven build (../<module>/target). Set BOOTSTRAP5_ARTIFACTS
# to a folder of released artifacts to test those instead, e.g. the assets of a GitHub release, or the 2.x
# jars from Nexus to compare the JSP line with the JavaScript one:
#   BOOTSTRAP5_ARTIFACTS=/path/to/release-3.0.1 bash ci.build.sh
#
# 2.x ships the three modules as jars; 3.x ships bootstrap5-core as a jar and the two others as JavaScript
# modules (.tgz), which run on the javascript-modules-engine shipped with Jahia. To test another engine
# version, set JS_ENGINE_VERSION (e.g. JS_ENGINE_VERSION=1.3.1): it is then installed before the first
# JavaScript module.
source ./set-env.sh
set -e

SKINS_VERSION=8.2.0
# CKEditor 5 for rich text fields: the suite checks rich text editing with CKEditor 4 and with CKEditor 5
CKEDITOR5_VERSION=1.0.1
MODULES="bootstrap5-core bootstrap5-components bootstrap5-templates-starter"

# assets/ is not versioned: it does not exist in a fresh checkout
mkdir -p assets
rm -f assets/*.jar assets/*.tgz
manifest=assets/provisioning.yml
install() {
    cat >> $manifest <<EOF
- installOrUpgradeBundle: '$1'
  autoStart: true
  uninstallPreviousVersion: true
EOF
}

echo "# Generated by ci.build.sh: do not edit." > $manifest
install "mvn:org.jahia.modules/skins/${SKINS_VERSION}"
install "mvn:org.jahia.modules/richtext-ckeditor5/${CKEDITOR5_VERSION}"
engine_installed=false
for module in $MODULES; do
    from=${BOOTSTRAP5_ARTIFACTS:-../${module}/target}
    artifact=$(find "$from" -maxdepth 1 \( -name "${module}-[0-9]*.jar" -o -name "${module}-[0-9]*.tgz" \) \
        ! -name '*-sources.jar' | sort | tail -1)
    if [[ -z "$artifact" ]]; then
        echo "No ${module} jar or tgz in ${from}: build the modules first (mvn clean install), or set BOOTSTRAP5_ARTIFACTS."
        exit 1
    fi
    if [[ "$artifact" == *.tgz && "$engine_installed" == false && -n "${JS_ENGINE_VERSION:-}" ]]; then
        install "mvn:org.jahia.modules/javascript-modules-engine/${JS_ENGINE_VERSION}"
        engine_installed=true
    fi
    cp "$artifact" assets/
    install "$(basename "$artifact")"
done

echo "Assets ready:"
ls -la assets/
cat $manifest
